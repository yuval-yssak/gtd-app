/**
 * Coverage for the sync doctor (`lib/syncDoctor.ts` + `POST /maintenance/sync-doctor`).
 *
 * Each check corresponds to a shipped bug class; the tests seed the exact corrupt shape that class
 * leaves behind and assert (a) the doctor reports it, (b) a clean dataset reports healthy, and
 * (c) the ONLY write path — the opt-in poisoned-watermark restamp — writes precisely what it
 * reports and records ops so other devices converge.
 */
